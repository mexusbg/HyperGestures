import unittest

from tools.hgtools import aflags

DUMP = (
    "android.adpf.adpf_viewrootimpl_action_down_boost                enabled  - default read-only system\n"
    "com.android.wm.shell.enable_taskbar_on_phones                   disabled - default read-only system\n"
    "com.android.launcher3.some_flag                                 enabled  disabled (staged) server read-write system\n"
    "\n"
    "garbage line without columns\n"
)


class AflagsTest(unittest.TestCase):
    def test_converts_current_state_sorted(self):
        out = aflags.to_device_txt(DUMP)
        body = [l for l in out.splitlines() if l and not l.startswith("#")]
        self.assertEqual(body, [
            "android.adpf.adpf_viewrootimpl_action_down_boost=true",
            "com.android.launcher3.some_flag=true",
            "com.android.wm.shell.enable_taskbar_on_phones=false",
        ])

    def test_header_says_generated(self):
        self.assertTrue(aflags.to_device_txt(DUMP).startswith("# Generated by tools/hgtools/aflags.py"))

    def test_output_is_lf_only(self):
        self.assertNotIn("\r", aflags.to_device_txt(DUMP.replace("\n", "\r\n")))


if __name__ == "__main__":
    unittest.main()
