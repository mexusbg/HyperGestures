import com.google.devtools.ksp.gradle.KspAATask
import org.gradle.api.GradleException
import org.gradle.api.Project
import org.gradle.api.tasks.compile.JavaCompile
import org.jetbrains.kotlin.gradle.tasks.KotlinCompile
import java.util.zip.ZipFile

/** Written into the stub jar by tools/framework-stub/AddInnerClasses.java once it has completed
 * the jar's InnerClasses attributes; see the marker check in [useDeviceFramework]. */
private const val INNER_CLASSES_MARKER = "META-INF/hg-innerclasses"

/**
 * Compiles this module against the device's own framework (hidden APIs included).
 *
 * The stub jar is generated by tools/framework-stub/make-framework-stub.sh from the phone's
 * framework.jar. It must come FIRST on the compile classpath, ahead of the SDK android.jar,
 * so that hidden members of public classes (e.g. Context.getIApplicationThread) resolve.
 * It is compile-only: at runtime the device's boot classpath supplies these classes.
 *
 * Kotlin: AGP 9's built-in Kotlin and the classic `org.jetbrains.kotlin.android` plugin both
 * create tasks of the same class, `org.jetbrains.kotlin.gradle.tasks.KotlinCompile`, so one
 * typed `withType` covers either toolchain. That type is visible here because buildSrc now
 * carries AGP and the Kotlin Gradle plugin on its own classpath (buildSrc/build.gradle.kts);
 * phase 0 had to find these tasks by name and use reflection, because AGP (and the KGP it
 * drives) then lived in the root project's classloader, which buildSrc cannot see.
 *
 * KSP (KSP2, `KspAATask`) gets the same treatment. It only reads declarations, but a class the
 * SDK android.jar also has would otherwise be taken from android.jar (KSP puts the boot classpath
 * first), and then its hidden nested classes do not exist: Dagger in :launcher failed on
 * `android.widget.TextClock.ClockEventDelegate` that way. (KSP also needs the stub's InnerClasses
 * attributes complete; tools/framework-stub/AddInnerClasses.java.)
 *
 * Why `doFirst`: reading `classpath`/`libraries` at configuration time crashes with a
 * NullPointerException for JavaCompile — AGP wires the variant's classpath onto these tasks
 * lazily, after our configuration action runs. Prepending at execution time sidesteps the
 * ordering. The stub is also a regular `compileOnly` dependency, so it is still a tracked task
 * input; `doFirst` only moves it to the front.
 *
 * Stale-stub guard: a jar built by an old copy of make-framework-stub.sh (before AddInnerClasses
 * existed, or copied in from another worktree) has complete class data but incomplete InnerClasses
 * attributes, and fails KSP deep inside Dagger resolution with a confusing error (task-7 report §4
 * fix 1) rather than here. AddInnerClasses.java writes a `META-INF/hg-innerclasses` marker entry
 * once it has run; its absence means the fix has never run over this jar.
 *
 * Device-build guard: the marker also names the device build (`fingerprint=`), and it must equal
 * the committed tools/framework-stub/device-build.txt, which records the HyperOS build every
 * device-derived value in the tree comes from (and which the KernelSU module pins the phone to).
 * make-framework-stub.sh writes both; a mismatch means the stub and the checked-out tree describe
 * different firmware.
 */
fun Project.useDeviceFramework() {
    val stub = rootProject.file("prebuilts/device/framework.jar")
    val stamp = rootProject.file("tools/framework-stub/device-build.txt")
    val rerun = "re-run tools/framework-stub/make-framework-stub.sh"
    if (!stub.exists()) {
        throw GradleException("Missing $stub — run tools/framework-stub/make-framework-stub.sh first.")
    }
    val marker = ZipFile(stub).use { zip ->
        zip.getEntry(INNER_CLASSES_MARKER)?.let { e -> zip.getInputStream(e).use { it.readBytes().decodeToString() } }
    }
    if (marker == null) {
        throw GradleException(
            "$stub is a stale stub (missing $INNER_CLASSES_MARKER) — device framework stub is " +
                "stale — $rerun"
        )
    }
    fun fingerprintIn(text: String) =
        text.lineSequence().map { it.trim() }.firstOrNull { it.startsWith("fingerprint=") }
            ?.removePrefix("fingerprint=")?.takeIf { it.isNotEmpty() }
    val stubBuild = fingerprintIn(marker)
        ?: throw GradleException("$stub names no device build (old marker) — device framework stub is stale — $rerun")
    val treeBuild = (if (stamp.isFile) fingerprintIn(stamp.readText()) else null)
        ?: throw GradleException("$stamp is missing or has no fingerprint= line — $rerun")
    if (stubBuild != treeBuild) {
        throw GradleException(
            "$stub was built from $stubBuild, but $stamp records $treeBuild: $rerun with the " +
                "matching device files, or check out the tree for that build"
        )
    }
    dependencies.add("compileOnly", files(stub))
    tasks.withType(JavaCompile::class.java).configureEach {
        doFirst { classpath = files(stub) + classpath }
    }
    tasks.withType(KotlinCompile::class.java).configureEach {
        doFirst { libraries.setFrom(listOf(stub) + libraries.from.toList()) }
    }
    tasks.withType(KspAATask::class.java).configureEach {
        doFirst { kspConfig.libraries.setFrom(listOf(stub) + kspConfig.libraries.from.toList()) }
    }
}
